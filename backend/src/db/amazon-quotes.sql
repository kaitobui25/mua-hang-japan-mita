-- Additive quote storage; never imports customer URLs into the catalog.
CREATE TABLE IF NOT EXISTS amazon_quote_settings (
  id integer PRIMARY KEY CHECK (id=1),
  version integer NOT NULL DEFAULT 1,
  delivery_days integer NOT NULL DEFAULT 7 CHECK (delivery_days BETWEEN 0 AND 90),
  updated_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO amazon_quote_settings(id) VALUES(1) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS amazon_quotes (
  id uuid PRIMARY KEY,
  snapshot jsonb NOT NULL,
  observed_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  order_id uuid REFERENCES orders(id),
  CHECK (expires_at=observed_at+interval '15 minutes')
);
CREATE INDEX IF NOT EXISTS amazon_quotes_expiry_idx ON amazon_quotes(expires_at);
CREATE TABLE IF NOT EXISTS amazon_quote_rate_limits (
  bucket text PRIMARY KEY,
  window_start timestamptz NOT NULL,
  attempts integer NOT NULL
);
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS quote_snapshot jsonb;
-- Different Amazon offers (or a catalog item and an Amazon quote) may have the same ASIN.
-- Preserve existing rows while replacing the legacy (order_id,asin) composite key.
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS line_id bigint GENERATED BY DEFAULT AS IDENTITY;
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='order_items'::regclass AND contype='p'
    AND pg_get_constraintdef(oid)='PRIMARY KEY (order_id, asin)') THEN
    ALTER TABLE order_items DROP CONSTRAINT order_items_pkey;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='order_items'::regclass AND contype='p') THEN
    ALTER TABLE order_items ADD CONSTRAINT order_items_pkey PRIMARY KEY (line_id);
  END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS order_items_catalog_unique_idx ON order_items(order_id,asin) WHERE quote_snapshot IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS order_items_quote_unique_idx ON order_items(order_id,((quote_snapshot->>'id'))) WHERE quote_snapshot IS NOT NULL;
